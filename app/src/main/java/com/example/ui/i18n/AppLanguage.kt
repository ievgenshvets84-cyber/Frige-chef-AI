val LocalAppStrings = compositionLocalOf { Translations.DE }
val LocalAppLanguage = compositionLocalOf { AppLanguage.DE }

class LanguageManager(context: Context) {
    private val prefs = context.getSharedPreferences("fridgechef_prefs", Context.MODE_PRIVATE)
    private val _currentLanguage = MutableStateFlow(loadInitialLanguage())
    val currentLanguage: StateFlow<AppLanguage> = _currentLanguage.asStateFlow()

    private fun loadInitialLanguage(): AppLanguage {
        val saved = prefs.getString("selected_language", null)
        return AppLanguage.entries.find { it.code == saved } ?: AppLanguage.DE
    }

    fun setLanguage(language: AppLanguage) {
        prefs.edit().putString("selected_language", language.code).apply()
        _currentLanguage.value = language
    }
}
